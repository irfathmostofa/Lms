export const dictionaries = { bn, en } as const;
export type Dictionary = typeof en;
export type MessageKey = string;

function lookup(dict: Dictionary, key: string): string | undefined {
  const parts = key.split('.');
  let current: unknown = dict;
  for (const part of parts) {
    if (!current || typeof current !== 'object' || !(part in current)) return undefined;
    current = (current as Record<string, unknown>)[part];
  }
  return typeof current === 'string' ? current : undefined;
}

export function translate(dict: Dictionary, key: string, vars?: Vars): string {
  const template = lookup(dict, key) ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] === undefined ? `{${name}}` : String(vars[name]),
  );
}

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

export function modeLabel(dict: Dictionary, mode: string) {
  if (mode === 'online') return dict.course.online;
  if (mode === 'offline') return dict.course.offline;
  if (mode === 'hybrid') return dict.course.hybrid;
  return mode;
}

export function lessonLabel(dict: Dictionary, count: number) {
  return `${count} ${count === 1 ? dict.course.lesson : dict.course.lessons}`;
}
